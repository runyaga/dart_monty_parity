#!/usr/bin/env python3
"""Score dart_monty_core's parity outcomes against pydantic-monty's, per capability row.

usage:
  python3 -I tool/parity/score.py OUTCOMES [--backends vm,dart2js,dart2wasm]
         [--expected DIR] [--json FILE] [--markdown FILE]
         [--assert-baseline] [--assert-rows] [--assert-current FILE]
         [--assert-e0 [FILE] [--engine worker|session]] [--assert-worker] [--assert-gate [FILE]]
         [--target [FILE] [--assert-target]]

OUTCOMES holds core-<backend>.json per case (tool/parity/run.py) and, for the
probe suites, per probe. EXPECTED (default tool/parity/expected) holds the
upstream's outcomes, generated by the reference oracle (pydantic-monty at the
tool/upstream pin) and bound to the cases by tool/parity/manifest.json.

Each case cell is classed MATCH (every compared field equals the oracle's),
DIVERGE, REFUSED (core refused what the case asked: a refusal the row's rule
names, or limits core declined), NO-OUTCOME (the runner produced nothing) or
NO-ORACLE. A row's status on a backend follows from its cases
(tool/parity/rows.json):

  PRESENT  every case MATCH
  PARTIAL  at least one case MATCH, not all
  ABSENT   no case MATCH, and not every case REFUSED (a row of REFUSED and
           DIVERGE cases is ABSENT)
  REFUSED  every case REFUSED

PARTIAL is strict: it needs a case that matches upstream in full, every
compared field equal. A field that merely resembles upstream's (the same text
in another type, the same value without identity) does not make a match.

A row rule may carry named exceptions: a tolerated difference, each with its
reason. Only the exceptions in KEPT_EXCEPTIONS exist, each ignoring one named
field where the difference is actually present; a rows.json that names any
other fails. Nothing else is tolerated.

--assert-rows fails when a re-measured row's status differs from the status
recorded for it in rows.json under the backend's `expect` (the baseline
measured at dart_monty_core 5873ec5); --assert-baseline fails when a PRESENT
count over the 185 in-scope manifest rows differs from the one recorded for
the architecture (re-measured rows from this run, the rest as recorded), and
on arm64 when the FFI count differs from the manifest's frozen baseline other
than by the rows rows.json lists under `rescored` (rows whose status these
scoring rules decide differently from the manifest's method).

Expectations are per CPU architecture. The baseline was measured on arm64;
`platforms` in rows.json (and in the current-baseline file) lists, per other
architecture, the rows whose status measurably differs there and that
architecture's PRESENT totals, each with its cause. The architecture comes
from OUTCOMES/platform.json, written by tool/parity/run.py; an architecture
with no entry fails.

--assert-current FILE compares instead with the baseline recorded for the
current tree (tool/parity/baseline-current.json): every case's class within
every re-measured row, every row's status, on every backend, and the PRESENT
totals. A change that moves a case or a row updates that file, with the move
listed under `deltas`.

--target [FILE] (default tool/parity/m3-target.json) also scores the M3 parity target: the in-scope
manifest rows M3 owns, each with the backends it must be PRESENT on (the rest of the 185 are `excluded`,
each under a named clause). It prints per-area PRESENT counts and every target row's status per backend
(a row with no parity case keeps its recorded baseline status, marked `*`). A row passes on a backend when it
is PRESENT there or an `allowed` entry (an approved exception: its kind, status, backends, reason and cite)
accepts the status it has; an `allowed` entry on a backend where the row is now PRESENT is STALE and fails.
Shown, never fatal, unless --assert-target (landed at the cut). The file itself must be consistent (every
in-scope row in exactly one list, a valid `allowed`): an inconsistent file exits non-zero either way.
An `allowed` entry may carry `evidenced_by` ({path, tests, exercises} items: the core tests that evidence a
row no binding exposes); `--core DIR` checks each named file exists in that core checkout and holds each test
title, and a mismatch exits non-zero like an inconsistent file.

--assert-e0 [FILE] (default tool/parity/e0.json) scores the E0 suite instead:
the worker engine's outcomes (`worker-<backend>.json`, run.py --engine
worker), or with --engine session the session engine's
(`session-<backend>.json`, run.py --engine session), against upstream's, every field compared with worker_compare.py (shared
objects and sandbox ids up to relabelling, strings exactly), no exceptions
tolerated. It fails unless every counted case is MATCH on every backend. A case listed
under `deferred` is shown as DEFERRED and not counted, and fails once it
matches on every backend (it then leaves `deferred`); it must still have
an outcome and an oracle on every backend. The case list must
equal the files in tool/parity/cases/<suite>.

--assert-worker scores the worker engine's value cases (rows.json: each row's
`worker` sets; the top-level `worker` block), compared as --assert-e0 compares:

  pre_cutover  must MATCH on every backend; a missing outcome or oracle fails
  diverge      a recorded divergence (worker.diverge): must differ in exactly
               its recorded fields, with its recorded worker value, on every
               backend; fails once it matches (it then moves to pre_cutover)
  cutover      shown, not asserted (measured on the cutover candidate), but it
               must have an outcome and an oracle on every backend
  also         not a set: cases another row's set owns, that this row maps too
               (a case is scored once, in its own set)

Every case file in the worker suite must be in exactly one set. Each negative
control in `worker.controls` mutates a pre-cutover case's real worker outcome
on every backend and must turn its MATCH into DIVERGE.

--assert-gate [FILE] (default tool/parity/c1-gate.json) scores the C1 gate:
the session engine's outcomes (`session-<backend>.json`, run.py --engine
session) for every case and probe of each gated row's `session` rule in
rows.json. Cases are compared as --assert-e0 compares them; probes as the
core engine's are (probes_compare.py), but with no named exception: a
suspension's position is compared. A case the session ran without
something it asks for (an `unsupported` entry: a limit, a policy, host
objects, a restore) is UNSUPPORTED, never MATCH. Whatever its stage, a case
must record a value or an exception for every feed, and a probe its events. A row is gated once its stage is
`landed`: then every case and probe of it must MATCH on every backend. A row
of a later stage is shown, not asserted. Whatever its stage, every case and
probe must have an outcome on every backend (a probe the session cannot run
yet records `unimplemented`, shown as PENDING) and an oracle, and the rules
must be complete: a `session` rule covers each of its row's core cases and
probes or names why not (`not_run`), names only cases and probes that exist,
and carries no named exception; the manifest gates every `session` rule,
every stage gates a row, and every case of the `session` suite and every
`sp_*` oracle probe is in a gated rule.
"""

