UUID = re.compile(r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}')
NUM = re.compile(r'\d+(\.\d+)?')
ALL_CODES = ['V', 'E', 'P', 'O', 'X', 'H', 'C']
E_PARTS = ['Et', 'Em', 'Ef', 'Ed']  # exception type, message, frames, structured data
FIELD = {'V': 'value', 'P': 'prints', 'O': 'os_calls', 'X': 'ext_calls', 'H': 'host_calls'}
CONFIG_KEYS = ('inputs', 'limits', 'os_policy', 'fs', 'cwd', 'mount_close')


# ------------------------------------------------------------------ compare
def norm(v):
    """Re-sorts sets, drops display-only float text, hidden `_` keys, uuids and measured limit amounts."""
    if isinstance(v, str):
        v = UUID.sub('<uuid>', v)
        return NUM.sub('N', v) if 'limit exceeded: ' in v else v
    if isinstance(v, list):
        return [norm(x) for x in v]
    if isinstance(v, dict):
        if v.get('t') == 'float':
            return {'t': 'float', 'bits': v.get('bits')}
        # A proxy's sandbox ids are the worker comparison's (worker_compare.py); this path never compared them.
        proxy = v.get('t') in ('proxy', 'typeproxy')
        d = {k: norm(x) for k, x in v.items()
             if not k.startswith('_') and not (proxy and k in worker_compare.ID_FIELDS)}
        if d.get('t') in ('set', 'frozenset'):
            d['items'] = sorted(d['items'], key=lambda e: json.dumps(e, sort_keys=True))
        return d
    return v


def exc_part(e, part):
    if not e:
        return e
    return e.get({'Et': 'type', 'Em': 'message', 'Ef': 'traceback', 'Ed': 'data'}[part])


def expand(codes: list[str]) -> list[str]:
    """`E` stands for all four exception parts."""
    out = []
    for c in codes:
        out.extend(E_PARTS if c == 'E' else [c])
    return out


# The only tolerated differences. Each ignores fields where the difference is
# actually present: `ignore` (case rows: field codes) or `ignore_keys` (probe
# rows: event keys).
KEPT_EXCEPTIONS = {
    'rename-missing-message': 'ignore',
    'payload-host-type': 'ignore_keys',
    'no-suspension-position': 'ignore_keys',
}


def check_exceptions(rules: dict) -> None:
    """Fails on any exception that is not one of KEPT_EXCEPTIONS, in the form it is kept in."""
    bad = []
    for row, rule in rules.items():
        for ex in rule.get('exceptions', []):
            form = KEPT_EXCEPTIONS.get(ex.get('name'))
            if form is None or form not in ex or set(ex) - {'name', 'reason', 'case', 'probe', 'backends', form}:
                bad.append(f"{row}: {ex.get('name')}")
    if bad:
        sys.exit(f'rows.json names exceptions score.py does not tolerate: {bad} (kept: {sorted(KEPT_EXCEPTIONS)})')


def compare_steps(ref: dict, got: dict, codes: list[str]) -> list[str]:
    """Codes of the compared fields that differ."""
    bad = []
    rs, gs = ref.get('steps') or [], got.get('steps') or []
    for code in codes:
        if code == 'C':
            unsup = got.get('unsupported') or {}
            if any(k.split('.')[0] in CONFIG_KEYS for k in unsup):
                bad.append('C')
            continue
        if code in E_PARTS:
            rv = [norm(exc_part(s.get('exception'), code)) for s in rs]
            gv = [norm(exc_part(s.get('exception'), code)) for s in gs]
        else:
            rv = [norm(s.get(FIELD[code])) for s in rs]
            gv = [norm(s.get(FIELD[code])) for s in gs]
        if rv != gv:
            bad.append(code)
    return bad


def is_refusal(got: dict, rule: dict) -> bool:
    if got.get('refused'):
        # Core declined the case's limits; a limit core has no field for at all is ABSENT, not REFUSED.
        unsup = got.get('unsupported') or {}
        return not any(k in unsup for k in rule.get('absent_if_unsupported', []))
    for needle in (rule.get('refusal') or {}).get('message_contains', []):
        for s in got.get('steps') or []:
            e = s.get('exception') or {}
            if needle in (e.get('message') or ''):
                return True
    return False


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def classify_case(cid: str, backend: str, rule: dict, out: Path, expected: Path,
                  engine: str = 'core') -> tuple[str, list[str], list[str]]:
    """-> (class, differing codes, names of the exceptions that changed the verdict)."""
    ref = load(expected / cid / f"{rule.get('oracle', 'ref-py')}.json")
    got = load(out / cid / f'{engine}-{backend}.json')
    if got is None or got.get('runner_error'):
        return 'NO-OUTCOME', ['!'], []
    if is_refusal(got, rule):
        return 'REFUSED', [], []
    if ref is None or ref.get('runner_error'):
        return 'NO-ORACLE', ['?'], []
    codes = expand(rule.get('compare', ALL_CODES))
    applied = []
    for ex in rule.get('exceptions', []):
        if ex.get('case') not in (None, cid) or backend not in ex.get('backends', [backend]):
            continue
        before = compare_steps(ref, got, codes)
        ignore = set(expand(ex['ignore']))
        if ignore & set(before):  # only when the tolerated difference is actually there
            codes = [c for c in codes if c not in ignore]
            applied.append(ex['name'])
    bad = compare_steps(ref, got, codes)
    return ('MATCH' if not bad else 'DIVERGE'), bad, applied


def row_status(classes: list[str]) -> str:
    """Strict: PARTIAL needs at least one full MATCH; REFUSED needs every case REFUSED; else ABSENT."""
    counted = [c for c in classes if c != 'NO-ORACLE']
    if not counted:
        return 'UNVERIFIED'
    n = sum(c == 'MATCH' for c in counted)
    if n == len(counted):
        return 'PRESENT'
    if n:
        return 'PARTIAL'
    if all(c == 'REFUSED' for c in counted):
        return 'REFUSED'
    return 'ABSENT'


# ------------------------------------------------------------------ probes
def probe_status(row: str, rule: dict, backend: str, out: Path, expected: Path) -> tuple[str, list[dict]]:
    """Probe suites: each probe's transcript equals the oracle's (with the row's named exceptions)."""
    from probes_compare import judge  # noqa: PLC0415 (local module, same dir)

    cells = []
    for pid in rule['probes']:
        ref = load(expected / pid / f"{rule.get('oracle', 'ref-py')}.json")
        got = load(out / pid / f'core-{backend}.json')
        cls, why, applied = judge(pid, ref, got, rule)
        cells.append({'case': pid, 'class': cls, 'differs': why, 'exceptions': applied})
    return row_status([c['class'] for c in cells]), cells


# ------------------------------------------------------------------ worker engine
def classify_worker(cid: str, backend: str, out: Path, expected: Path,
                    local_refusal: bool = False, got: dict | None = None,
                    engine: str = 'worker') -> tuple[str, list[str]]:
    """A worker- or session-engine case on [backend]: (class, differing codes), compared by worker_compare."""
    ref = load(expected / cid / 'ref-py.json')
    got = got if got is not None else load(out / cid / f'{engine}-{backend}.json')
    if got is None or got.get('runner_error'):
        return 'NO-OUTCOME', ['!']
    if ref is None or ref.get('runner_error'):
        return 'NO-ORACLE', ['?']
    if ref.get('strings_rewritten'):
        return 'NO-ORACLE', ['strings_rewritten']  # mark the case exact_strings to compare it
    bad = worker_compare.compare(ref, got, local_refusal)
    if 'budget' in bad:
        return 'NO-VERDICT', bad  # the search ran out: neither a match nor evidence of a difference
    return ('MATCH' if not bad else 'DIVERGE'), bad


def case_index() -> dict[str, dict]:
    """Every case file, by id."""
    out = {}
    for p in sorted(CASES.glob('*/*.json')):
        c = json.loads(p.read_text())
        out[c['id']] = {**c, '_suite': p.parent.name}
    return out


def worker_sets(rules_doc: dict) -> tuple[dict[str, tuple[str, str]], list[str]]:
    """case -> (row, set) over every row's `worker` block, and the problems found building it."""
    where: dict[str, tuple[str, str]] = {}
    problems = []
    for row, rule in rules_doc['rows'].items():
        for kind, cases in (rule.get('worker') or {}).items():
            if kind == 'also':
                continue  # read below: a mapping, not a set
            if kind not in ('pre_cutover', 'diverge', 'cutover'):
                problems.append(f'{row}: unknown worker set {kind!r}')
                continue
            for cid in cases:
                if cid in where:
                    problems.append(f'{cid} is in {where[cid]} and in {(row, kind)}')
                where[cid] = (row, kind)
    # `also`: cases another row's set owns, that this row maps too (a case is scored once, in its own set).
    for row, rule in rules_doc['rows'].items():
        also = (rule.get('worker') or {}).get('also', [])
        if not isinstance(also, list) or not also or len(set(also)) != len(also):
            if 'also' in (rule.get('worker') or {}):
                problems.append(f'{row}: worker `also` must be a non-empty list of distinct cases')
            continue
        for cid in also:
            if cid not in where:
                problems.append(f'{row}: worker `also` names {cid}, which is in no row\'s worker set')
            elif where[cid][0] == row:
                problems.append(f'{row}: worker `also` names {cid}, which the row already owns')
    return where, problems


def recorded_divergence(rec: dict, cls: str, bad: list[str], got: dict | None) -> bool:
    """Whether a worker outcome [got] diverges from upstream exactly as the record [rec] says.

    It must DIVERGE in exactly rec['differs'], and its first step must carry the recorded worker value
    (`worker_value`) and, when the record has one, the recorded worker exception (`worker_exception`:
    type, message, traceback and data compared)."""
    if cls != 'DIVERGE' or bad != rec['differs'] or got is None:
        return False
    steps = [dict(st) for st in got.get('steps') or []]
    if steps:
        if 'worker_value' in rec:
            steps[0]['value'] = rec['worker_value']
        if 'worker_exception' in rec:
            steps[0]['exception'] = rec['worker_exception']
    codes = ['V'] + (['Et', 'Em', 'Ef', 'Ed'] if 'worker_exception' in rec else [])
    if 'worker_value' not in rec and 'worker_exception' not in rec:
        return False
    return worker_compare.compare({'steps': steps}, got, codes=codes) == []


def assert_worker(outcomes: Path, expected: Path, backends: list[str],
                  markdown: Path | None, json_out: Path | None) -> int:
    """The worker engine's value rows: every pre-cutover case MATCH, every recorded divergence DIVERGE."""
    doc = json.loads(RULES.read_text())
    spec = doc['worker']
    where, problems = worker_sets(doc)
    cases = case_index()
    for cid in where:
        if cid not in cases:
            problems.append(f'{cid}: listed, but no tool/parity/cases/*/{cid}.json')
    for cid, c in cases.items():
        if c['_suite'] == spec['suite'] and cid not in where:
            problems.append(f'{cid}: in tool/parity/cases/{spec["suite"]} but in no worker set')
    for cid in spec.get('not_run', {}):
        if cid not in cases or cid in where:
            problems.append(f'{cid}: under worker.not_run, but {"in a worker set" if cid in where else "no such case"}')
    for cid, (row, kind) in where.items():
        if (kind == 'diverge') != (cid in spec.get('diverge', {})):
            problems.append(f'{cid}: a `diverge` case needs its record in worker.diverge, and only one has one')
    if problems:
        sys.exit('rows.json worker sets: ' + '; '.join(problems))
    table = {cid: {b: classify_worker(cid, b, outcomes, expected, bool(cases[cid].get('local_refusal')))
                   for b in backends} for cid in where}
    lines = ['Worker engine, value rows (rows.json `worker`)', '',
             '| row | case | set | ' + ' | '.join(backends) + ' |', '|---|---|---|' + '---|' * len(backends)]
    for row, rule in doc['rows'].items():
        for kind in ('pre_cutover', 'diverge', 'cutover'):
            for cid in (rule.get('worker') or {}).get(kind, []):
                cells = [table[cid][b][0] + (f' `{"".join(table[cid][b][1])}`' if table[cid][b][1] else '')
                         for b in backends]
                lines.append(f'| {row} | {cid} | {kind} | ' + ' | '.join(cells) + ' |')
    for row, rule in doc['rows'].items():
        for cid in (rule.get('worker') or {}).get('also', []):
            cells = [table[cid][b][0] for b in backends if cid in table]
            lines.append(f'| {row} | {cid} | also ({where[cid][0]}) | ' + ' | '.join(cells) + ' |')
    lines.append('')
    rc = 0
    def ran_every_feed(cid: str, b: str) -> bool:
        """One step per feed, each with a value or a recorded exception (a staged refusal counts)."""
        got = load(outcomes / cid / f'worker-{b}.json') or {}
        steps = got.get('steps') or []
        return len(steps) == len(cases[cid].get('feeds') or [cases[cid].get('code')]) and all(
            isinstance(s, dict) and (s.get('value') is not None
                                     or isinstance((s.get('exception') or {}).get('type'), str))
            for s in steps)

    def as_recorded(cid: str, b: str) -> bool:
        """A recorded divergence differs in exactly its recorded fields, with the recorded worker value."""
        cls, bad = table[cid][b]
        return recorded_divergence(spec['diverge'][cid], cls, bad, load(outcomes / cid / f'worker-{b}.json'))

    for b in backends:
        pre = [c for c, (_, k) in where.items() if k == 'pre_cutover']
        div = [c for c, (_, k) in where.items() if k == 'diverge']
        cut = [c for c, (_, k) in where.items() if k == 'cutover']
        n = sum(table[c][b][0] == 'MATCH' for c in pre)
        nd = sum(as_recorded(c, b) for c in div)
        # Shown, not asserted, but they must still run, every feed, against an oracle.
        unrun = [c for c in cut if table[c][b][0] in ('NO-OUTCOME', 'NO-ORACLE') or not ran_every_feed(c, b)]
        ok = n == len(pre) and nd == len(div) and not unrun
        rc |= not ok
        lines.append(f'{"PASS" if ok else "FAIL"} worker values on {b}: {n}/{len(pre)} pre-cutover cases MATCH, '
                     f'{nd}/{len(div)} recorded divergences as recorded'
                     + (f'; cutover cases that did not run every feed against an oracle: {", ".join(unrun)}' if unrun else ''))
    for cid, (row, kind) in where.items():
        if kind == 'diverge' and all(table[cid][b][0] == 'MATCH' for b in backends):
            rc = 1
            lines.append(f'FAIL worker: {cid} ({row}) now MATCHES on every backend; move it to pre_cutover')
    lines.append('')
    controls = []
    for ctl in spec.get('controls', []):
        cid, mutation = ctl['case'], ctl['mutation']
        if where.get(cid, ('', ''))[1] != 'pre_cutover':
            rc = 1
            lines.append(f'FAIL control {mutation} on {cid}: not a pre-cutover case')
            continue
        for b in backends:
            got = load(outcomes / cid / f'worker-{b}.json')
            if got is None or table[cid][b][0] != 'MATCH':
                verdict, why = 'FAIL', f'the unmutated case is {table[cid][b][0]}'
            else:
                got = copy.deepcopy(got)
                if not worker_compare.mutate(got, mutation):
                    verdict, why = 'FAIL', 'nothing to mutate'
                else:
                    cls, bad = classify_worker(cid, b, outcomes, expected, bool(cases[cid].get('local_refusal')), got)
                    verdict, why = ('PASS', f'mutated: DIVERGE {"".join(bad)}') if cls == 'DIVERGE' else (
                        'FAIL', f'mutated: {cls}')
            rc |= verdict != 'PASS'
            controls.append({'case': cid, 'mutation': mutation, 'backend': b, 'verdict': verdict, 'why': why})
            lines.append(f'{verdict} control {mutation} on {cid} ({b}): {why}')
    lines.append('')
    for cid, rec in spec.get('diverge', {}).items():
        lines.append(f'recorded divergence {cid} ({where[cid][0]}, differs in {"".join(rec["differs"])}): {rec["why"]}')
    for cid, why in spec.get('not_run', {}).items():
        lines.append(f'not run through the worker: {cid}: {why}')
    for d in spec.get('divergences', []):
        lines.append(f'recorded divergence {d["name"]} ({", ".join(d["rows"])}): {d["what"]}')
    text = '\n'.join(lines) + '\n'
    print(text)
    if markdown:
        markdown.write_text(text)
    if json_out:
        json_out.write_text(json.dumps({'cases': {
            cid: {'row': where[cid][0], 'set': where[cid][1],
                  **{b: {'class': c, 'differs': d} for b, (c, d) in by_b.items()}}
            for cid, by_b in table.items()}, 'controls': controls}, indent=1) + '\n')
    return rc


# ------------------------------------------------------------------ the C1 gate
GATE = ROOT / 'tool/parity/c1-gate.json'


def gate_problems(gate: dict, rows: dict, cases: dict[str, dict], expected: Path) -> list[str]:
    """What makes the gate manifest or the rows' `session` rules incomplete."""
    problems = []
    stages = gate['stages']
    if set(gate['landed']) - set(stages):
        problems.append(f"landed stages {sorted(set(gate['landed']) - set(stages))} are not in `stages`")
    for stage in sorted(set(stages) - set(gate['rows'].values())):
        problems.append(f'stage {stage!r} gates no row: landing it would assert nothing')
    for row, stage in gate['rows'].items():
        if stage not in stages:
            problems.append(f'{row}: stage {stage!r} is not in `stages`')
        rule = rows.get(row)
        if rule is None or 'session' not in rule:
            problems.append(f'{row}: gated, but rows.json has no `session` rule for it')
            continue
        sess = rule['session']
        if set(sess) - {'cases', 'probes', 'not_run'}:
            problems.append(f'{row}: the session rule has {sorted(set(sess) - {"cases", "probes", "not_run"})}; '
                            'the session engine tolerates no named exception')
        listed = set(sess.get('cases', [])) | set(sess.get('probes', []))
        if not listed:
            problems.append(f'{row}: the session rule names no case or probe')
        for cid in rule.get('cases', []) + rule.get('probes', []):
            if cid not in listed and cid not in sess.get('not_run', {}):
                problems.append(f'{row}: {cid} is a case of the row but neither in its session rule nor in `not_run`')
        for cid in sess.get('not_run', {}):
            if cid in listed or cid not in rule.get('cases', []) + rule.get('probes', []):
                problems.append(f'{row}: `not_run` {cid} must be a core case of the row that the session rule omits')
        for cid in sess.get('cases', []):
            if cid not in cases:
                problems.append(f'{row}: no case file for {cid}')
        for pid in sess.get('probes', []):
            if pid in cases or not (expected / pid / 'ref-py.json').exists():
                problems.append(f'{row}: no oracle probe {pid}')
    for row, rule in rows.items():
        if 'session' in rule and row not in gate['rows']:
            problems.append(f'{row}: has a session rule but no stage in the gate manifest')
    # The session engine's own cases and probes exist only for the gate: each must be in a gated rule.
    suite, prefix = 'session', 'sp_'
    gated = {kind: {cid for row in gate['rows'] for cid in (rows.get(row, {}).get('session') or {}).get(kind, [])}
             for kind in ('cases', 'probes')}
    for cid, c in cases.items():
        if c['_suite'] == suite and cid not in gated['cases']:
            problems.append(f'{cid}: in tool/parity/cases/{suite} but in no gated session rule')
    for d in sorted(expected.glob(f'{prefix}*')):
        if d.name not in gated['probes']:
            problems.append(f'{d.name}: a session probe of the oracle but in no gated session rule')
    for stage in set(gate.get('core_gated', {})) - set(stages):
        problems.append(f'`core_gated` names {stage!r}, which is not in `stages`')
    d1 = gate.get('d1_rules')
    if d1 is not None:
        # One case or probe per D1-calls rule (rules 1-7), each in the session rule of a row of the `d1_calls` stage.
        if sorted(d1) != [str(n) for n in range(1, 8)]:
            problems.append(f'`d1_rules` must name rules 1-7, one each; it has {sorted(d1)}')
        carried = {cid for row, st in gate['rows'].items() if st == 'd1_calls'
                   for kind in ('cases', 'probes') for cid in (rows.get(row, {}).get('session') or {}).get(kind, [])}
        for rule, cid in d1.items():
            if cid not in carried:
                problems.append(f'D1-calls rule {rule}: {cid} is in no session rule of a `d1_calls` row')
        for cid in sorted(carried - set(d1.values())):
            problems.append(f'`d1_calls` carries {cid}, which is no D1-calls rule\'s case or probe')
        if 'd1_calls' not in stages:
            problems.append('`d1_rules` is set but `stages` has no `d1_calls`')
    return problems


def ran_in_full(cid: str, kind: str, backend: str, out: Path, cases: dict[str, dict]) -> bool:
    """A case recorded one step per feed, each a value or an exception; a probe recorded events or what it waits for."""
    got = load(out / cid / f'session-{backend}.json') or {}
    if kind == 'probes':
        return bool(got.get('events')) or bool(got.get('unimplemented'))
    steps = got.get('steps') or []
    return len(steps) == len(cases[cid].get('feeds') or [cases[cid].get('code')]) and all(
        isinstance(s, dict) and (s.get('value') is not None or isinstance((s.get('exception') or {}).get('type'), str))
        for s in steps)


def classify_session_case(cid: str, backend: str, out: Path, expected: Path, case: dict) -> tuple[str, list[str]]:
    """A session-engine case on [backend]: UNSUPPORTED when the session could not apply something the case asks
    (a limit, a policy, host objects, a restore), whatever its outcome; else as the worker engine's."""
    cls, why = classify_worker(cid, backend, out, expected, bool(case.get('local_refusal')), engine='session')
    unsupported = sorted((load(out / cid / f'session-{backend}.json') or {}).get('unsupported') or {})
    # A missing outcome or oracle outranks UNSUPPORTED.
    if cls in ('NO-OUTCOME', 'NO-ORACLE') or not unsupported:
        return cls, why
    return 'UNSUPPORTED', unsupported


def classify_session_probe(pid: str, backend: str, out: Path, expected: Path) -> tuple[str, list[str]]:
    """A session-engine probe on [backend], judged with no named exception."""
    from probes_compare import judge  # noqa: PLC0415 (local module, same dir)

    got = load(out / pid / f'session-{backend}.json')
    ref = load(expected / pid / 'ref-py.json')
    # A runner error or a missing oracle outranks `unimplemented`.
    usable_ref = ref is not None and not ref.get('runner_error')
    if got is not None and got.get('unimplemented') and not got.get('runner_error') and usable_ref:
        return 'PENDING', [str(got['unimplemented'])]
    cls, why, _ = judge(pid, ref, got, {})
    return cls, why


def assert_gate(spec_path: Path, outcomes: Path, expected: Path, backends: list[str],
                markdown: Path | None, json_out: Path | None) -> int:
    """The C1 gate: every case and probe of a landed row MATCH on every backend."""
    gate = json.loads(spec_path.read_text())
    rows = json.loads(RULES.read_text())['rows']
    cases = case_index()
    problems = gate_problems(gate, rows, cases, expected)
    if problems:
        sys.exit(f'{spec_path}: ' + '; '.join(problems))
    landed = set(gate['landed'])
    table: dict[str, dict[str, tuple[str, list[str]]]] = {}
    lines = [f"The C1 gate through the `{gate['engine']}` engine; landed: "
             f"{', '.join(st for st in gate['stages'] if st in landed)}", '', '| row | stage | case or probe | ' + ' | '.join(backends) + ' |',
             '|---|---|---|' + '---|' * len(backends)]
    rc = 0
    for stage in gate['stages']:
        for row, row_stage in gate['rows'].items():
            if row_stage != stage:
                continue
            sess = rows[row]['session']
            for kind in ('cases', 'probes'):
                for cid in sess.get(kind, []):
                    if cid not in table:
                        table[cid] = {b: (classify_session_case(cid, b, outcomes, expected, cases[cid])
                                          if kind == 'cases' else classify_session_probe(cid, b, outcomes, expected))
                                      for b in backends}
                    cells = [table[cid][b][0] + (f' `{"; ".join(table[cid][b][1])}`' if table[cid][b][1] else '')
                             for b in backends]
                    gated = stage in landed
                    lines.append(f'| {row} | {stage}{"" if gated else " (pending)"} | {cid} | ' + ' | '.join(cells) + ' |')
                    for b in backends:
                        cls = table[cid][b][0]
                        if gated and cls != 'MATCH':
                            rc = 1
                            lines.append(f'FAIL gate: {cid} ({row}, {stage}) is {cls} on {b}')
                        elif cls in ('NO-OUTCOME', 'NO-ORACLE'):
                            rc = 1
                            lines.append(f'FAIL gate: {cid} ({row}, {stage}) has {cls} on {b}; every case and probe must run')
                        elif not ran_in_full(cid, kind, b, outcomes, cases):
                            rc = 1
                            lines.append(f'FAIL gate: {cid} ({row}, {stage}) did not run in full on {b} '
                                         '(a case: a value or an exception for every feed; a probe: its events)')
            for cid, why in sess.get('not_run', {}).items():
                lines.append(f'| {row} | {stage} | {cid} | not run: {why} |' + ' |' * (len(backends) - 1))
    lines.append('')
    for b in backends:
        gated = [(cid, row) for row, st in gate['rows'].items() if st in landed
                 for kind in ('cases', 'probes') for cid in rows[row]['session'].get(kind, [])]
        n = sum(table[cid][b][0] == 'MATCH' for cid, _ in gated)
        lines.append(f'{"PASS" if n == len(gated) else "FAIL"} gate on {b}: {n}/{len(gated)} gated cases and probes MATCH')
    text = '\n'.join(lines) + '\n'
    print(text)
    if markdown:
        markdown.write_text(text)
    if json_out:
        json_out.write_text(json.dumps({'landed': sorted(landed), 'rows': gate['rows'], 'cases': {
            cid: {b: {'class': c, 'differs': d} for b, (c, d) in by_b.items()} for cid, by_b in table.items()}},
            indent=1) + '\n')
    return rc


